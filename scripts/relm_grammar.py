"""
Writes a GBNF grammar (llama.cpp) that only accepts RELM using the tags in a RELM table.

  uv run -q --project common/robbie-lib-py python scripts/relm_grammar.py --table config/relm_table.yaml

The grammar enforces:
  - only tags from the table, written exactly (no params, no whitespace inside tags)
  - instant macros (nothing to undo) are self-closing, e.g. <wink/>
  - span macros wrap text and must be closed in order, e.g. <happy>...</happy>
  - text has no markdown characters (* # `), since it is spoken
"""
import argparse
import sys

from relm.table import Table

TEXT_RULE = r'text ::= [^<>*#`]+'


def grammar(table: Table) -> str:
    instants = [m.name for m in table.macros.values() if m.instant]
    spans = [m.name for m in table.macros.values() if not m.instant]

    lines = [
        "# Generated by scripts/relm_grammar.py from a RELM table. Do not edit.",
        "root ::= content",
        "content ::= text? (tag text?)*",
        TEXT_RULE,
    ]
    tag = []
    if instants:
        tag.append("instant")
        names = " | ".join(f'"{n}"' for n in instants)
        lines.append(f'instant ::= "<" ({names}) "/>"')
    # Rule names are numbered, macro names can hold characters GBNF rule names can't.
    for i, name in enumerate(spans):
        rule = f"span{i}"
        tag.append(rule)
        lines.append(f'{rule} ::= "<{name}>" content "</{name}>"  # {name}')
    if not tag:
        return "\n".join(["root ::= text?", TEXT_RULE]) + "\n"
    lines.insert(3, "tag ::= " + " | ".join(tag))
    return "\n".join(lines) + "\n"


def main(argv=None):
    p = argparse.ArgumentParser(description="RELM table to GBNF grammar.")
    p.add_argument("--table", required=True, help="the RELM to IRELM table (YAML)")
    p.add_argument("--out", help="output file (default: stdout)")
    args = p.parse_args(argv)

    text = grammar(Table.load(args.table))
    if args.out:
        with open(args.out, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
